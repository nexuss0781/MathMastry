#!/usr/bin/env node
// Embeds drizzle SQL migrations into a TypeScript module so the API can create
// its schema at runtime on Wasmer Edge, where drizzle-kit is unavailable.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const apiRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(apiRoot, "drizzle");
const outFile = join(apiRoot, "src", "db", "migrations.generated.ts");

const files = readdirSync(migrationsDir)
  .filter((file) => file.endsWith(".sql"))
  .sort();

const migrations = files.map((file) => {
  const sql = readFileSync(join(migrationsDir, file), "utf8");
  return sql
    .split("--> statement-breakpoint")
    .map((statement) => statement.trim())
    .filter(Boolean);
});

const header = `// AUTO-GENERATED by scripts/embed-migrations.mjs. Do not edit by hand.\n`;
const body = `export interface EmbeddedMigration {\n  file: string;\n  statements: string[];\n}\n\nexport const embeddedMigrations: EmbeddedMigration[] = ${JSON.stringify(
  files.map((file, index) => ({ file, statements: migrations[index] })),
  null,
  2,
)};\n`;

writeFileSync(outFile, header + body);
console.log(`Embedded ${files.length} migration file(s) into ${outFile}`);
